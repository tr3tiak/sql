SELECT
    e.id,
    e.name,
    e.description,
    e.price,                                         
    CEIL(e.price / 82.1911)::INTEGER AS price_usd     
FROM excursion e
ORDER BY e.id;


SELECT
    t.id AS tour_id,
    COUNT(rc.city_id) AS cities_count
FROM tour t
LEFT JOIN route_city rc ON rc.route_id = t.route_id
GROUP BY t.id
HAVING COUNT(rc.city_id) <> 2
ORDER BY cities_count, t.id;
